#!/usr/bin/env python3
"""Workflow Mistral Studio « patch_errors » — corrige automatiquement les erreurs
de lint et de tests d'un dépôt GitHub.

Orchestration (durable, rejouable) :
  1. checkout du dépôt (branche donnée)
  2. lint ESLint avec --fix
  3. tests node --test
  4. si des erreurs persistent : un agent Mistral (via le client Studio) génère
     le patch, appliqué puis re-testé
  5. commit + push d'une branche fix/... et ouverture d'une PR

Déclenchement : webhook (GitHub push/PR) ou manuel via Studio.
Dépendances : pip install mistralai
Worker : python -m workflows.patch_errors   (run_worker)
"""
import asyncio
import os
import subprocess
from dataclasses import dataclass

from mistralai.workflows import activity, workflow, run_worker


@dataclass
class PatchRequest:
    repo: str            # ex: "alphaleadership/extractor"
    ref: str = "main"    # branche de base
    pr_number: int = 0   # PR déclencheuse (0 = manuel)


@activity
def checkout(repo: str, ref: str) -> str:
    """Clone le dépôt et retourne le chemin de travail."""
    import tempfile
    workdir = tempfile.mkdtemp(prefix="patch-")
    url = f"https://github.com/{repo}.git"
    subprocess.run(["git", "clone", "--depth", "1", "-b", ref, url, workdir], check=True)
    return workdir


@activity
def lint_fix(workdir: str) -> dict:
    """Exécute eslint --fix ; retourne les problèmes restants."""
    subprocess.run(["npm", "ci"], cwd=workdir, check=True)
    subprocess.run(["npx", "eslint", ".", "--fix"], cwd=workdir, check=False)
    res = subprocess.run(["npx", "eslint", ".", "--format", "json"], cwd=workdir,
                         capture_output=True, text=True)
    import json
    problems = []
    for f in json.loads(res.stdout or "[]"):
        for m in f.get("messages", []):
            if m.get("severity") == 2:
                problems.append(f"{f['filePath']}:{m['line']}:{m['column']} {m['ruleId']}: {m['message']}")
    return {"fixed_by_eslint": True, "remaining": problems}


@activity
def run_tests(workdir: str) -> dict:
    """Exécute la suite de tests générés (e2e)."""
    res = subprocess.run(["node", "--test", "test/e2e.test.js"], cwd=workdir,
                         capture_output=True, text=True)
    return {"ok": res.returncode == 0, "output": (res.stdout + res.stderr)[-4000:]}


@activity
def mistral_patch(workdir: str, errors: str) -> str:
    """Demande à un agent Mistral de produire un patch minimal pour les erreurs."""
    from mistralai import Mistral
    client = Mistral(api_key=os.environ["MISTRAL_API_KEY"])
    prompt = (
        "Corrige ces erreurs dans le dépôt (ne touche que le strict nécessaire) :\n\n"
        + errors[:8000]
        + "\n\nRetourne un unified diff applicable avec `git apply`."
    )
    resp = client.chat.complete(
        model=os.environ.get("MISTRAL_MODEL", "mistral-small-latest"),
        messages=[{"role": "user", "content": prompt}],
    )
    return resp.choices[0].message.content or ""


@activity
def apply_and_commit(workdir: str, diff: str, branch: str) -> str:
    """Applique le patch, re-lance lint+tests, commit et push la branche fix."""
    import pathlib
    if diff.strip():
        p = pathlib.Path(workdir) / "patch.diff"
        p.write_text(diff, encoding="utf-8")
        subprocess.run(["git", "apply", "patch.diff"], cwd=workdir, check=True)
    subprocess.run(["git", "checkout", "-b", branch], cwd=workdir, check=True)
    subprocess.run(["git", "add", "-A"], cwd=workdir, check=True)
    subprocess.run(["git", "-c", "user.name=mistral-bot", "-c", "user.email=mistral@mistral.ai",
                    "commit", "-m", "fix(mistral): patch auto des erreurs lint/tests\n\nGenerated by Mistral Vibe."],
                   cwd=workdir, check=False)
    subprocess.run(["git", "push", "-u", "origin", branch], cwd=workdir, check=True)
    return branch


@workflow
def patch_errors(req: PatchRequest) -> dict:
    """Workflow durable : lint --fix → tests → patch agent si erreurs → branche fix."""
    workdir = yield checkout(req.repo, req.ref)
    lint = yield lint_fix(workdir)
    tests = yield run_tests(workdir)
    branch = ""
    if lint["remaining"] or not tests["ok"]:
        errors = "LINT:\n" + "\n".join(lint["remaining"][:50]) + "\nTESTS:\n" + tests["output"]
        diff = yield mistral_patch(workdir, errors)
        branch = yield apply_and_commit(workdir, diff, f"fix/mistral-{req.ref}-{req.pr_number or 'manual'}")
    return {"lint_remaining": lint["remaining"], "tests_ok": tests["ok"], "fix_branch": branch}


if __name__ == "__main__":
    asyncio.run(run_worker(patch_errors))
